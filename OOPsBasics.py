# In Programming language, there are basically two approaches to write a program/code :-

# 1.) PROCEDURAL PROGRAMMING
# This programming includes the functions, user input, self logic..etc...

# 2.) OBJECT ORIENTED PROGRAMMING
# The basic idea of using OOPs in Python is to use classes & objects to represent real world concepts.

# ~ A Class is a blueprint or template for creating an object.
# ~ it defines the Properties(data or state of an object) & Methods(actions or behaviours that an object can perform)

# ~ An Object is the instance of a class & it contains its own data and methods

# ^ KEY FEATURES OF OOPs IN PYTHON :-

# ~ ENCAPSULATION 
# It means storing things inside a capsule.

# ~ INHERITANCE 
# It allows new classes to be created that inherit the properties and methods of an existing class.

# ~ POLYMORPHISM
# It means that objects of different classes can be treated as if they were objects of a common class.