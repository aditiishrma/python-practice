# VARIABLES AND DATA TYPES
# String Data type
a="Aditi Sharma"
print(a)
b="Ram ji"
print(b)
# Int Data type
c = 9
d = 100
# Operations performed on them
print(c*d)
print(c+d)
print(c/d)
# Type of variable
d = None
print(d)
# Output showing the type of any a, b , c , d
print("The type of a is" , type(a))
print("The type of c is" , type(c))
print("The type of d is" , type(d))

#List are mutable
list = ['Aditi Sharma' , 20 , ("Radhey")]
print(list)

#Tuples are immutable
tuple = ("Rab ne bana di jodi" , (9,10), 23.3)
print(tuple)

#Dictionary are mutable , basically the key-value pairs
dict = {"India" : "Delhi", "Pakistan" : "Islamabad"}
print(dict)

# Operators
print(15+7)
print(15-7)
print(15/7)
print(20//5) # kitni baar divisible hai
print(15*7)
print(15%5) #remainder
